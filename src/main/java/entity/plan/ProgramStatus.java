package entity.plan;

/**
 * A student's status in a program on their plan. The values mean the following:
 * <ul>
 *   <li>{@code ENROLLED}: the student is admitted to the program.
 *   <li>{@code INTENDED}: the student plans to apply to the program.
 * </ul>
 */
public enum ProgramStatus {
    ENROLLED, INTENDED
}
